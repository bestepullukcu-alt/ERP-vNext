using Diten.ManagementGovernanceService.Application.Features.Dws.Commands;
using DwsAuthorizationManifest = Diten.ManagementGovernanceService.Application.Modules.Dws.DwsAuthorizationManifest;
using MediatR;

namespace Diten.ManagementGovernanceService.Application.Features.Dws.Handlers.CommandHandlers;

public sealed class UpdateStructureMetadataHandler(IDwsFunctionalValidator<UpdateStructureMetadataCommand> validator, IFu16DwsFunctionalAuthorization authorization, IMod0117DwsContextValidator contexts, IDwsStructureVisibilityPort visibility, IDwsFunctionalCommandPort commands)
    : IRequestHandler<UpdateStructureMetadataCommand, Response<UpdateStructureMetadataResult>>
{
    public Task<Response<UpdateStructureMetadataResult>> Handle(UpdateStructureMetadataCommand request, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(request);
        return DwsFunctionalResponse.ExecuteAsync(async () => { validator.Validate(request); var security = await DwsExistingStructureSecurity.CaptureAsync(request.Request.StructureDefinitionId, request.Context, nameof(UpdateStructureMetadataCommand), DwsAuthorizationManifest.RequireExact(nameof(UpdateStructureMetadataCommand)), authorization, contexts, visibility, cancellationToken); await DwsExistingStructureSecurity.RevalidateAsync(request.Context, security, authorization, contexts, visibility, cancellationToken); return await commands.UpdateStructureMetadataAsync(request.Request, request.Context, cancellationToken); });
    }
}
